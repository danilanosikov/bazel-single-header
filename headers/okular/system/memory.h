#ifndef oku_system_memory

	// @описание: запрашивает память у операционной системы
	// @приём: bytes: размер запрошиваемой памяти в байтах
	// @ошибка: NULL: память не была выделена
	// @возврат: n: адрес выделенной памяти
	void* oku_system_memory_create(unsigned long bytes);

	// @описание: возвращает запрошенную память под управление операционной системы
	// @приём: address: адрес запрошенной памяти
	// @приём: size: размер запрошенной памяти
	// @ошибка: -1: не указано, где искать ссылку
	// @возврат: 0: ссылка не указывает на память
	// @возврат: n: количество байт отданных под управление операционной системе
	int oku_system_memory_destroy(void *address, unsigned long size);

	#define oku_system_memory oku_system_memory
#endif
