#include <okular/system/memory.h>
#include "common.h"

// @описание: проверяет первичное выделение памяти программистом
// @возврат: 0: успешное окончание тестирования
// @возврат: -1: ошибка выделения памяти
int main(void)
{

	// @описание:
	// память хранящая результат тестирования
	int result;

	// @заметка:
	// по умолчанию функция завершится успешно,
	// если во время тестирования значение этой
	// переменной не будет изменено
	result = 0;

	// @описание:
	// переменная, хранящая адрес памяти,
	// запрошенной у системы проверяемой функцией
	void* memory;

	// @заметка:
	// вызов проверяемой функции
	memory = oku_system_memory_create(sample);

	// @заметка:
	// функция не выделила памяти программе при правильном её вызове
	if(!memory) { result = -__LINE__; goto end;}

	// @заметка
	// отчистка памяти перед возвратом результата,
	// результат отчистки не проверяется,
	// так как этот тест проверяет только первичное выделение памяти
	//
	// @заметка: goto:
	// выполнено на случай появления других проверок,
	// чтобы при первой же ошибке заканчивать тестирование
	// а не городить if-else и не проваливаться
	// в следующую проверку при ошибке
	end: oku_system_memory_destroy(memory, sample);


	// @заметка: возврат результата
	return result;

}
