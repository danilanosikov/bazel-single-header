#include <okular/system/memory.h>
#include <common.h>

// @описание:
// проверяет является ли память читаемой и записываемой
// @ошибка: n: код ошибки
// @возврат: 0: успешное окончание тестирования
int main(void)
{
	// @описание:
	// память хранящая результат тестирования
	int result;

	// @заметка:
	// по умолчанию функция завершится успешно,
	// если во время тестирования значение этой
	// переменной не будет изменено
	result = 0;

	// @описание: память для хранения результата повторного выделения
	void *memory;

	// @описание:
	// первичное выделение памяти
	memory = oku_system_memory_create(sample);

	// @заметка:
	// нельзя проверить функцию на добросовестность
	// без получения явного результата от неё
	if(!memory) { result = -__LINE__; goto end; }

	// создаём переменную, хранящую адрес,
	// по которому можно записать данные в память
	int* handle = (int*) memory;

	// запоминаем значение данных до их изменения
	int sample = *handle;

	// записываем данные
	*handle = 8;
	*handle += 1;

	// читаем данные
	int value = *handle;

	// записанные данные не совпали с прочитанными
	if(value != 9) { result = __LINE__; goto end; }


	// @заметка: goto:
	// выполнено на случай появления других проверок,
	// чтобы при первой же ошибке заканчивать тестирование
	// а не городить if-else и не проваливаться
	// в следующую проверку при ошибке
	end:
		// @заметка
		// отчистка памяти перед возвратом результата,
		// результат отчистки не проверяется,
		// так как этот тест проверяет только первичное выделение памяти
		oku_system_memory_destroy(memory, sample);

	// @заметка:
	// возвращаем код успешного завершения тестирования,
	// если программа не была прервана до его окончания
	return 0;
}
