// @заметка:
// вставка реализаций интерфейсов
// взаимодействия с ядром linux
#include <sys/sysinfo.h>
#include <stdint.h>



// @описание: тест проверяет - достаточно ли памяти на устройстве
// для корректного прохождения последующего тестирования
//
// @ошибка: n: на устройстве замечены проблемы с памятью,
// а значит результат последующего тестирования с ещё большей вероятностью
// не будет отображать реальное поведение программы
//
// @возврат: 0: успешное завершение тестирования,
// памяти достаточно для корректного тестирования
int main(void) {
	// память для хранения результатов опроса ядра
	struct sysinfo info;

	// память для хранения промежуточных результатов операций
	int result;

	// опрос ядра
	result = sysinfo(&info);

	// проверка успешности опроса ядра
	if (result != 0) {
		return -__LINE__;
	}

	// проверка корректности данных полученных,
	// в результате опроса ядра
	// если размерность разбиения памяти
	// не задана - значит ядро не смогло
	// корректно ответить программе
	if (info.mem_unit == 0) {
		return -__LINE__;
	}

	// проверка корректности размера выделяемой памяти
	if (0>=(intmax_t)sample) {
		return -__LINE__;
	}

	// размер памяти в единицах разбиения памяти
	uintmax_t required_units = (uintmax_t)sample/ (uintmax_t)info.mem_unit;

	// проверка корректности размерности выделяемой памяти
	// когда размерность не попадает размер разбиения
	// размер округляется в большую сторону
	if ((uintmax_t)sample % (uintmax_t)info.mem_unit != 0) {
		required_units += 1;
	}

	// количество свободной памяти в единицах разбиения памяти
	uintmax_t free_units = (uintmax_t)info.freeram;

	// проверка корректности результата,
	// сообщающего количество свободной,
	// полученного при опросе ядра
	if (free_units <= UINTMAX_MAX - (uintmax_t)info.freehigh) {
		free_units += (uintmax_t)info.freehigh;
	}

	// проверка проверяющая - достаточно ли у системы памяти для
	// обеспечения корректных условий для качественного проведения
	// последующего тестирования
	if (free_units < required_units) {
		return -__LINE__;
	}

	// успешное завершение тестирования
	return 0;
}
